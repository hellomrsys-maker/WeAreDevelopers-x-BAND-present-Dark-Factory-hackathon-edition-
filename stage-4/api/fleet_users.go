// VirtualUser represents a high-profile client in the 100-user fleet.
type VirtualUser struct {
	ID               string             `json:"id"`
	Name             string             `json:"name"`
	Email            string             `json:"email"`
	Phone            string             `json:"phone"`
	City             string             `json:"city"`
	Tier             string             `json:"tier"`
	BalanceCents     int64              `json:"balance_cents"`
	BalanceFormatted string             `json:"balance_formatted"`
	Dietary          string             `json:"dietary"`
	AvatarColor      string             `json:"avatar_color"`
	OrderCount       int                `json:"order_count"`
	Orders           []OrderHistoryItem `json:"orders"`
}

// OrderHistoryItem represents an authentic order in a client's real-time history.
type OrderHistoryItem struct {
	OrderID        string   `json:"order_id"`
	RestaurantID   string   `json:"restaurant_id"`
	RestaurantName string   `json:"restaurant_name"`
	PartySize      int      `json:"party_size"`
	TimeSlot       string   `json:"time_slot"`
	Date           string   `json:"date"`
	Items          []string `json:"items"`
	TotalCents     int64    `json:"total_cents"`
	TotalFormatted string   `json:"total_formatted"`
	Status         string   `json:"status"` // "CONFIRMED & SETTLED"
	TxHash         string   `json:"tx_hash"`
	CreatedAt      string   `json:"created_at"`
}

// ClientOrderRequest represents placing a real-time order from the mobile simulator
type ClientOrderRequest struct {
	UserID       string   `json:"user_id"`
	RestaurantID string   `json:"restaurant_id"`
	PartySize    int      `json:"party_size"`
	TimeSlot     string   `json:"time_slot"`
	Date         string   `json:"date"`
	Items        []string `json:"items"`
	TotalCents   int64    `json:"total_cents"`
	Notes        string   `json:"notes,omitempty"`
}

